/**
 * Deterministic article builders. Inputs are a published release and weekly editions; output is article
 * content. Sentences are templates filled by code from release values, so an article can only say what the
 * release says, and every block cites the release paths it read. No model writes or edits the text.
 *
 * Builders are pure: no I/O, no clock. scripts/lambo/research.ts supplies dates and writes files.
 */
import { compactUsd, percent } from "../../format.ts";
import { CHAIN_NAME } from "../core/identity.ts";
import type { CoinPublic, NarrativePublic, ReleasePublic } from "../release/types.ts";
import type { EditionDoc } from "../service.ts";
import { editionCite, releaseCite } from "./cite.ts";
import type { Article, ArticleBlock, Citation } from "./types.ts";

export const GENERATOR = { name: "lambo-research-templates", version: "1.0.0" };

export const POLICY = {
  auto: "Daily and weekly articles restate one release or edition by template and are published without human review; they are labelled 'Not reviewed'.",
  pending:
    "Deep dives are published to local and preview builds as 'Pending review'. Production hides them until a named reviewer records a review (reviewer and time in the article file); no review is implied before that.",
};

export const ATTRIBUTION = {
  producer: "Generated by the LAMBLE research pipeline",
  drafting: "Text is filled from the cited release by fixed templates; no person wrote it and no language model drafted it.",
};

type Body = ArticleBlock[];
type Draft = Omit<Article, "publishedAt" | "updatedAt" | "generator" | "changelog" | "schemaVersion">;

const usd = (v: number | null) => (v === null ? "not available" : compactUsd(v, 2));
const pct = (v: number | null) => (v === null ? "not available" : percent(v, { digits: 1, signed: true }));
const share = (v: number | null) => (v === null ? "not available" : percent(100 * v, { digits: 1 }));
const day = (iso: string) => new Date(iso).toLocaleDateString("en-US", { timeZone: "UTC", month: "short", day: "numeric", year: "numeric" });
const lastDayOf = (endIso: string) => day(new Date(Date.parse(endIso) - 1000).toISOString());

function price(v: number | null): string {
  if (v === null) return "not available";
  if (v >= 1) return `$${v.toLocaleString("en-US", { maximumFractionDigits: 4 })}`;
  const digits = Math.min(12, Math.max(2, -Math.floor(Math.log10(v)) + 3));
  return `$${v.toFixed(digits)}`;
}

function p(text: string, ...cites: Citation[]): ArticleBlock {
  return { type: "p", text, cites };
}

export function slugify(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}

// ---------------------------------------------------------------- weekly

export function weeklyArticle(e: EditionDoc, releaseId: string): Draft {
  const c = (...ptr: (string | number)[]) => editionCite(e.id, e.revision, ...ptr);
  const m = e.market;
  const body: Body = [];
  const venues = [...m.venues].filter((v) => v.included && v.fees !== null).sort((a, b) => b.fees! - a.fees!);
  const narratives = [...e.narratives].sort((a, b) => b.volume.observed - a.volume.observed);
  const top = narratives.find((n) => n.collectedDuringWeek) ?? null;
  const emerging = narratives.filter((n) => n.emerging);
  const paused = narratives.filter((n) => n.pausedDuringWeek);

  body.push({ type: "h2", text: "Fees and creator earnings" });
  body.push(
    p(
      `The covered launchpad fee subtotal for ${e.id} (${day(e.interval.start)} to ${lastDayOf(e.interval.end)}, UTC) was ${usd(m.feeSubtotal.value)} across ${m.feeSubtotal.comparedOn.length} non-overlapping venues, ${pct(m.feeSubtotal.changePct)} against ${e.comparison.id}${m.feeSubtotal.scopeChanged ? " on the venues present in both weeks" : " on the same venues"}. ${m.excluded.length} venues that share a fee stream with another venue are reported individually and never added.`,
      c("market", "feeSubtotal", "value"),
      c("market", "feeSubtotal", "changePct"),
    ),
  );
  body.push(
    p(
      `Creator earnings — fees paid to coin creators and, depending on the venue's own definition, holders, referrers or traders — were ${usd(m.creatorEarnings.value)} across ${m.creatorEarnings.venues.length} venues that define them, ${pct(m.creatorEarnings.changePct)} week over week.`,
      c("market", "creatorEarnings", "value"),
      c("market", "creatorEarnings", "changePct"),
    ),
  );
  body.push({
    type: "facts",
    caption: `Largest venues in the subtotal, ${e.id}`,
    rows: venues.slice(0, 6).map((v) => ({
      label: v.name,
      value: `${usd(v.fees)} (${pct(v.feesChangePct)})`,
      note: v.shareOfSubtotal === null ? null : `${share(v.shareOfSubtotal)} of the subtotal`,
      cite: c("market", "venues", m.venues.indexOf(v), "fees"),
    })),
  });
  const shifts = e.venueChanges.filter((v): v is typeof v & { sharePoints: number } => v.sharePoints !== null).sort((a, b) => b.sharePoints - a.sharePoints);
  if (shifts.length >= 2) {
    const up = shifts[0]!;
    const down = shifts.at(-1)!;
    body.push(
      p(
        `By share of the subtotal, ${up.name} gained the most (${up.sharePoints >= 0 ? "+" : ""}${up.sharePoints.toFixed(1)} points) and ${down.name} lost the most (${down.sharePoints.toFixed(1)} points). A share shift says where fees moved, not why.`,
        c("venueChanges"),
      ),
    );
  }

  body.push({ type: "h2", text: "Narratives" });
  body.push(
    p(
      `Trading in the coins of the tracked narratives totalled ${usd(e.dedup.totalVolume)} for the week, counting a coin once when it belongs to more than one narrative (the per-narrative totals add up to ${usd(e.dedup.sumOfNarrativeTotals)}). This is the volume of identified coins across their indexed pools, not of the whole market.`,
      c("dedup", "totalVolume"),
      c("dedup", "sumOfNarrativeTotals"),
    ),
  );
  if (top) {
    const i = e.narratives.indexOf(top);
    body.push(
      p(
        `${top.title} carried the most volume among narratives collected during the week: ${usd(top.volume.observed)}${top.volume.complete ? "" : " (partial: some member-days were not observed)"}. ${top.emerging ? "It was first observed this week, so no week-over-week change is reported." : top.volumeChangePct === null ? `Its week-over-week change is withheld: ${top.comparable.members} of ${top.comparable.ofMembersInBothWeeks} members present in both weeks were fully observed in both, below the comparable-basket minimum.` : `On the ${top.comparable.members} members fully observed in both weeks, volume changed ${pct(top.volumeChangePct)}.`}`,
        c("narratives", i, "volume", "observed"),
        c("narratives", i, "comparable"),
      ),
    );
  }
  if (emerging.length) {
    body.push(
      p(
        `First observed this week: ${emerging.map((n) => n.title).join(", ")}. A narrative's first week has no meaningful prior week, so no change is reported for it.`,
        ...emerging.map((n) => c("narratives", e.narratives.indexOf(n), "emerging")),
      ),
    );
  }
  if (paused.length) {
    body.push(
      p(
        `Collection paused during the week: ${paused.map((n) => n.title).join(", ")}. Their members stay members; their totals after the pause are partial, not zero.`,
        ...paused.map((n) => c("narratives", e.narratives.indexOf(n), "pausedDuringWeek")),
      ),
    );
  }
  body.push({
    type: "list",
    items: narratives
      .filter((n) => n.collectedDuringWeek)
      .map((n) => ({
        text: `${n.title}: ${n.volume.coverage === 0 ? "no member-day observed" : `${usd(n.volume.observed)}${n.volume.complete ? "" : " (partial)"}`}, ${n.members} members, ${n.emerging ? "first observed this week" : n.volumeChangePct === null ? "change withheld" : `${pct(n.volumeChangePct)} on the comparable basket`}.`,
        cites: [c("narratives", e.narratives.indexOf(n), "volume")],
      })),
  });

  body.push({ type: "h2", text: "Breadth" });
  body.push(
    p(
      `${e.breadth.advancing} of the ${e.breadth.withPrices} tracked coins with prices at both ends of the week rose. The five most traded coins accounted for ${share(e.breadth.top5VolumeShare)} of deduplicated narrative volume.`,
      c("breadth", "advancing"),
      c("breadth", "top5VolumeShare"),
    ),
  );

  body.push({ type: "h2", text: "What to watch" });
  if (e.watch.length) {
    body.push({ type: "list", items: e.watch.map((w, i) => ({ text: `${w.subject}: ${w.condition}`, cites: [c("watch", i)] })) });
  } else {
    body.push(p("No published rule threshold is close for a collected narrative or its members.", c("watch")));
  }
  body.push({
    type: "callout",
    tone: e.status === "complete" ? "neutral" : "warning",
    text: `Edition status: ${e.status} (revision ${e.revision}, method ${e.methodVersion}). ${e.checks.map((x) => `${x.id}: ${x.passed ? "pass" : "fail"}`).join("; ")}.`,
  });

  return {
    slug: `state-of-the-trenches-${e.id.toLowerCase()}`,
    title: `State of the Trenches, ${e.id}: fees ${pct(m.feeSubtotal.changePct)} week over week`,
    dek: `Launchpad fees were ${usd(m.feeSubtotal.value)} across ${m.feeSubtotal.comparedOn.length} non-overlapping venues and creator earnings ${usd(m.creatorEarnings.value)}${top ? `; ${top.title} led narrative volume` : ""}.`,
    format: "weekly",
    dataCutoff: e.dataCutoff,
    releaseId: e.releaseId ?? releaseId,
    review: { status: "auto-published", reviewer: null, reviewedAt: null, policy: POLICY.auto },
    attribution: { ...ATTRIBUTION, byline: null },
    entities: { coins: [], narratives: narratives.map((n) => n.slug), weeks: [e.id], launchpads: venues.map((v) => v.slug) },
    confidence: e.status === "complete" ? "moderate" : "low",
    confidenceReason:
      e.status === "complete"
        ? "Every completeness check passed; narrative totals cover identified coins only and some members are partially observed."
        : "One or more completeness checks failed; totals are partial.",
    body,
    limitations: [
      m.feeSubtotal.scope,
      m.indexedActivity.scope,
      "Narrative volume covers identified member coins across their indexed pools; it is not all-market volume and can include wash or bot trading.",
      e.provenance,
    ],
  };
}

// ---------------------------------------------------------------- daily

export function dailyArticle(r: ReleasePublic, runDate: string, changes: { kind: string; summary: string; seq: number }[]): Draft {
  const c = (...ptr: (string | number)[]) => releaseCite(r.releaseId, ...ptr);
  const m = r.market;
  const collected = r.narratives.filter((n) => n.lifecycle.state === "collected");
  const movers = r.coins
    .filter((x) => x.collection.status === "collected" && x.market.volume24hRolling.value !== null)
    .sort((a, b) => b.market.volume24hRolling.value! - a.market.volume24hRolling.value!)
    .slice(0, 5);
  const body: Body = [
    {
      type: "facts",
      caption: `Market facts, release ${r.releaseId}`,
      rows: [
        { label: `Fee subtotal, day ending ${day(m.feeSubtotal.anchor ?? r.dataCutoff)}`, value: usd(m.feeSubtotal.value), note: `${m.feeSubtotal.included.length} non-overlapping venues`, cite: c("market", "feeSubtotal", "value") },
        { label: "Fee subtotal, last 7 settled days vs prior 7", value: pct(m.feeSubtotal.change7dPct), note: null, cite: c("market", "feeSubtotal", "change7dPct") },
        { label: "Coins created, rolling 24h (indexed)", value: m.indexed.created24 === null ? "not available" : m.indexed.created24.toLocaleString("en-US"), note: `${m.indexed.creationVenues} venues; Codex beta`, cite: c("market", "indexed", "created24") },
        { label: "Completions, rolling 24h (indexed)", value: m.indexed.completed24 === null ? "not available" : m.indexed.completed24.toLocaleString("en-US"), note: `${m.indexed.completionVenues} venues report completions`, cite: c("market", "indexed", "completed24") },
        { label: "Creator earnings, 7 settled days", value: usd(m.creatorEarnings.value7d), note: null, cite: c("market", "creatorEarnings", "value7d") },
      ],
    },
    { type: "h2", text: "Collected narratives, last 24 hours of data" },
    {
      type: "list",
      items: collected.map((n) => ({
        text: `${n.title}: ${usd(n.activity.volume24h.value)}${n.activity.volume24h.state === "stale" ? " (stale)" : ""}, ${n.memberCounts.open} members.`,
        cites: [c("narratives", n.slug, "activity", "volume24h")],
      })),
    },
    { type: "h2", text: "Most traded collected coins, rolling 24h" },
    {
      type: "list",
      items: movers.map((x) => ({
        text: `${x.symbol ?? x.address} (${CHAIN_NAME[x.chain]}): ${usd(x.market.volume24hRolling.value)} traded, price ${pct(x.market.priceChange24hRolling.value)} over 24 hours, circulating market cap ${usd(x.market.marketCap.value)}.`,
        cites: [c("coins", x.id, "market", "volume24hRolling"), c("coins", x.id, "market", "marketCap")],
      })),
    },
    p("Rolling 24-hour volume is as reported across all pools. Where a coin trades many times its market cap in a day, the volume can include wash or bot trading.", c("market")),
  ];
  if (changes.length) {
    body.push({ type: "h2", text: "Recorded changes" });
    body.push({ type: "list", items: changes.slice(0, 12).map((x) => ({ text: x.summary, cites: [c("changes", x.seq)] })) });
    if (changes.length > 12) body.push(p(`${changes.length - 12} more changes are in the changes feed.`, c("changes")));
  }
  return {
    slug: `daily-${runDate}`,
    title: `Daily facts, ${day(`${runDate}T00:00:00Z`)}`,
    dek: `Fee subtotal ${usd(m.feeSubtotal.value)} for the last settled day; ${m.indexed.created24?.toLocaleString("en-US") ?? "an unknown number of"} coins indexed as created in 24 hours; ${collected.length} narratives collected.`,
    format: "daily",
    dataCutoff: r.dataCutoff,
    releaseId: r.releaseId,
    review: { status: "auto-published", reviewer: null, reviewedAt: null, policy: POLICY.auto },
    attribution: { ...ATTRIBUTION, byline: null },
    entities: { coins: movers.map((x) => x.id), narratives: collected.map((n) => n.slug), weeks: [], launchpads: [] },
    confidence: "moderate",
    confidenceReason: "Restates validated release values; rolling provider windows and identified-coin volume have the scopes stated.",
    body,
    limitations: [m.feeSubtotal.scope, m.indexed.scope, m.rolling7d.note],
  };
}

// ---------------------------------------------------------------- coin deep dive

export function coinArticle(r: ReleasePublic, coin: CoinPublic): Draft {
  const c = (...ptr: (string | number)[]) => releaseCite(r.releaseId, "coins", coin.id, ...ptr);
  const label = coin.symbol ?? coin.address;
  const mk = coin.market;
  const methods = new Map(r.methods.holderComponents.map((x) => [x.id, x]));
  const withValue = coin.holders.components.filter((h) => h.measure.value !== null);
  const missing = coin.holders.components.filter((h) => h.measure.value === null);
  const vol = coin.charts.volumeDaily.filter((x) => x.value !== null && x.value > 0);
  const maxDay = vol.reduce<{ time: number; value: number | null } | null>((best, x) => (best === null || x.value! > best.value! ? x : best), null);
  const open = coin.memberships.filter((x) => x.effectiveTo === null);
  const b = coin.bottoming;
  const body: Body = [
    { type: "h2", text: "What it is" },
    p(
      `${label}${coin.name && coin.name !== coin.symbol ? ` (${coin.name})` : ""} is a ${CHAIN_NAME[coin.chain]} token at ${coin.address}. ${coin.identity.tokenCreatedAt ? `It was created on ${day(coin.identity.tokenCreatedAt)} (${coin.identity.tokenCreatedBasis ?? "basis not recorded"})` : "Its creation time is not recorded"}${coin.identity.originVenue ? `, with origin attributed to ${coin.identity.originVenue}: ${coin.identity.originStatus ?? "attribution basis not recorded"}` : ""}. LAMBLE first observed it on ${day(coin.identity.firstObservedAt)}.`,
      c("identity"),
    ),
    p(
      open.length
        ? `It is classified in ${open.map((x) => x.narrativeTitle).join(" and ")}. ${open[0]!.rationale ?? ""}`.trim()
        : "It has no open narrative membership.",
      ...open.map((x) => c("memberships", coin.memberships.indexOf(x))),
      ...open.flatMap((x) => x.evidence),
    ),
    { type: "h2", text: "Market" },
    {
      type: "facts",
      caption: `Latest snapshot, release ${r.releaseId}`,
      rows: [
        { label: "Price", value: price(mk.price.value), note: mk.price.state === "observed" ? null : mk.price.state, cite: c("market", "price") },
        { label: "Market cap (circulating)", value: usd(mk.marketCap.value), note: "Fully diluted value is not available from a validated source", cite: c("market", "marketCap") },
        { label: "Liquidity (top pair)", value: usd(mk.liquidity.value), note: null, cite: c("market", "liquidity") },
        { label: "Volume, rolling 24h", value: usd(mk.volume24hRolling.value), note: "All pools, as reported", cite: c("market", "volume24hRolling") },
        { label: "Volume, 7 complete days", value: usd(mk.volume7d.value), note: mk.volume7d.method ?? null, cite: c("market", "volume7d") },
        { label: "Change vs 7 days earlier", value: mk.change7d.value === null ? `not available (${mk.change7d.state.replace("_", " ")})` : pct(mk.change7d.value), note: mk.change7d.note ?? null, cite: c("market", "change7d") },
      ],
    },
    p(
      vol.length
        ? `Across the ${coin.charts.volumeDaily.length} UTC days in the chart window, the coin traded on ${vol.length} day(s); its busiest day was ${day(new Date(maxDay!.time * 1000).toISOString())} with ${usd(maxDay!.value)}. Days before the token existed count as zero; days that were not observed are gaps, not zero.`
        : "No daily volume was observed in the chart window.",
      c("charts", "volumeDaily"),
    ),
    { type: "h2", text: "Bottoming test" },
    p(
      b.state === "not_applicable"
        ? `The test does not apply: ${b.explanation}`
        : b.state === "insufficient_data"
          ? `${b.label}. ${b.explanation} ${b.conditions.map((x) => `${x.label}: ${x.detail}`).join(" ")}`
          : `${b.label} (stage ${b.stage} of 3). ${b.explanation}`,
      c("bottoming"),
    ),
    { type: "h2", text: "Holder analysis" },
    p(
      `${withValue.length} of 9 holder-analysis components have a value for this coin: ${withValue.map((h) => methods.get(h.id)?.label ?? h.id).join("; ") || "none"}. The other ${missing.length} need data no validated source provides yet (${[...new Set(missing.map((h) => methods.get(h.id)?.requires[0] ?? h.id))].slice(0, 3).join("; ")}), so no holder composite is computed.`,
      c("holders", "components"),
      c("holders", "composite"),
    ),
    ...withValue.map((h) =>
      p(
        `${methods.get(h.id)?.label ?? h.id}: ${h.measure.value === null ? "not available" : h.id === "relative.peer_performance" ? percent(100 * h.measure.value, { digits: 1, signed: true }) : h.measure.value.toFixed(3)}${h.measure.state === "stale" ? " (stale)" : ""}. ${h.measure.coverage?.scope ?? ""}`.trim(),
        c("holders", "components", coin.holders.components.indexOf(h)),
      ),
    ),
  ];
  if (coin.peers.length) {
    const priced = coin.peers.filter((x) => x.return7d !== null);
    body.push(
      p(
        `Peers are the other members of its narratives. ${priced.length ? `${priced.length} have a 7-day return: ${priced.slice(0, 5).map((x) => `${x.symbol ?? x.tokenId} ${pct(100 * x.return7d!)}`).join(", ")}.` : "None has a 7-day snapshot return in this release."}`,
        c("peers"),
      ),
    );
  }
  return {
    slug: `coin-${slugify(label)}-${coin.chain}-${coin.address.slice(0, 6).toLowerCase()}`,
    title: `${label} on ${CHAIN_NAME[coin.chain]}: what the record shows`,
    dek: `${usd(mk.volume7d.value)} traded over seven complete days, ${open.length ? `classified in ${open.map((x) => x.narrativeTitle).join(" and ")}` : "no open narrative"}; ${withValue.length} of 9 holder components measurable; bottoming test ${b.state.replace("_", " ")}.`,
    format: "coin-deep-dive",
    dataCutoff: r.dataCutoff,
    releaseId: r.releaseId,
    review: { status: "pending-review", reviewer: null, reviewedAt: null, policy: POLICY.pending },
    attribution: { ...ATTRIBUTION, byline: null },
    entities: { coins: [coin.id], narratives: open.map((x) => x.narrativeSlug), weeks: [], launchpads: coin.identity.originVenue ? [coin.identity.originVenue] : [] },
    confidence: withValue.length >= 5 && b.state === "evaluated" ? "moderate" : "low",
    confidenceReason: `Market data is observed, but ${missing.length} of 9 holder components and ${b.state === "evaluated" ? "no" : "the"} bottoming conditions lack validated inputs.`,
    body,
    limitations: [
      "Prices are daily-run snapshot samples, not candles; intraday moves are not observed.",
      "Holder balances, wallet-resolved trades and portfolio data are not collected by any enabled capability.",
      coin.collection.note,
    ],
  };
}

// ---------------------------------------------------------------- narrative deep dive

export function narrativeArticle(r: ReleasePublic, n: NarrativePublic, editions: EditionDoc[]): Draft {
  const c = (...ptr: (string | number)[]) => releaseCite(r.releaseId, "narratives", n.slug, ...ptr);
  const a = n.activity;
  const members = [...n.members].filter((x) => x.share7d !== null).sort((x, y) => y.share7d! - x.share7d!);
  const weekRows = editions
    .map((e) => ({ e, row: e.narratives.find((x) => x.slug === n.slug) }))
    .filter((x): x is { e: EditionDoc; row: EditionDoc["narratives"][number] } => Boolean(x.row));
  const body: Body = [
    { type: "h2", text: "What it is" },
    p(n.summary ?? `${n.title} groups coins classified under this story.`, c("summary")),
  ];
  if (n.story) {
    body.push(p(`Most recent observation of the story (${n.story.observedAt ? day(n.story.observedAt) : "date not recorded"}): ${n.story.notice ?? ""} ${n.story.interpretation ?? ""}`.trim(), ...(n.story.evidence ? [n.story.evidence] : []), c("story")));
  }
  body.push(
    p(
      `Evidence on record: ${n.evidence.projectClaims.length} project claim(s), ${n.evidence.independent.length} independent source(s) and ${n.evidence.posts.length} post(s). ${n.evidence.note}`,
      ...n.evidence.projectClaims.slice(0, 3).map((x) => x.id),
      ...n.evidence.independent.slice(0, 3).map((x) => x.id),
      ...n.evidence.posts.slice(0, 3).map((x) => x.id),
    ),
    { type: "h2", text: "Activity" },
    {
      type: "facts",
      caption: `Member volume, release ${r.releaseId}`,
      rows: [
        { label: "Last 24 hours of data", value: usd(a.volume24h.value), note: a.volume24h.state === "stale" ? (a.volume24h.note ?? "stale") : null, cite: c("activity", "volume24h") },
        { label: "Last 7 days of data", value: usd(a.volume7d.value), note: null, cite: c("activity", "volume7d") },
        { label: "30 days (current basket applied retrospectively)", value: usd(a.volume30d.value), note: "Reconstructed", cite: c("activity", "volume30d") },
        { label: "Week over week", value: n.trend === "new" ? "not shown: first observed this week" : n.trend === "not_collected" ? "not shown: not collected" : pct(a.change7dPct), note: null, cite: c("activity", "change7dPct") },
      ],
    },
    p(a.volumeScope, c("activity", "volumeScope")),
  );
  if (a.caveat) body.push({ type: "callout", tone: "warning", text: a.caveat });
  body.push(
    { type: "h2", text: "Members" },
    p(
      `${n.memberCounts.open} open memberships (${n.memberCounts.collected} collected daily, ${n.memberCounts.paused} paused, ${n.memberCounts.inactive} inactive)${n.memberCounts.ended ? ` and ${n.memberCounts.ended} ended` : ""}. ${members.length ? `The largest member by 7-day volume share is ${members[0]!.symbol ?? members[0]!.tokenId} at ${share(members[0]!.share7d)}; the Herfindahl index is ${n.concentration.hhi ?? "not available"} on a 0–10,000 scale.` : ""}`,
      c("memberCounts"),
      c("concentration"),
    ),
    {
      type: "list",
      items: members.slice(0, 8).map((x) => ({
        text: `${x.symbol ?? x.tokenId} (${CHAIN_NAME[x.chain]}${x.originVenue ? `, ${x.originVenue}` : ""}): ${share(x.share7d)} of 7-day volume, member since ${day(x.effectiveFrom)}.`,
        cites: [c("members", n.members.indexOf(x))],
      })),
    },
    { type: "h2", text: "History" },
    {
      type: "list",
      items: n.lifecycle.history.map((h, i) => ({
        text: `${h.state.replace("_", " ")} from ${day(h.from)}${h.to ? ` to ${day(h.to)}` : " to now"}${h.reason ? `: ${h.reason}` : "."}`,
        cites: [c("lifecycle", "history", i)],
      })),
    },
  );
  if (weekRows.length) {
    body.push({
      type: "list",
      items: weekRows.map(({ e, row }) => ({
        text: `${e.id}: ${usd(row.volume.observed)}${row.volume.complete ? "" : " (partial)"}; ${row.volumeChangePct === null ? "change withheld" : `${pct(row.volumeChangePct)} on the comparable basket`}.`,
        cites: [editionCite(e.id, e.revision, "narratives", e.narratives.indexOf(row), "volume")],
      })),
    });
  }
  if (n.overlap.length) {
    body.push(p(`Shared members with other narratives: ${n.overlap.map((o) => `${o.tokens} with ${o.narrativeSlug}`).join(", ")}. Market totals count such coins once.`, c("overlap")));
  }
  return {
    slug: `narrative-${n.slug}`,
    title: `${n.title}: members, money and history`,
    dek: `${usd(a.volume7d.value)} of member volume over the last seven days of data, ${n.memberCounts.open} members, ${n.lifecycle.state.replace("_", " ")} since ${day(n.lifecycle.since)}.`,
    format: "narrative-deep-dive",
    dataCutoff: r.dataCutoff,
    releaseId: r.releaseId,
    review: { status: "pending-review", reviewer: null, reviewedAt: null, policy: POLICY.pending },
    attribution: { ...ATTRIBUTION, byline: null },
    entities: { coins: n.members.map((x) => x.tokenId), narratives: [n.slug], weeks: weekRows.map((x) => x.e.id), launchpads: [] },
    confidence: n.evidence.independent.length > 0 && n.lifecycle.state === "collected" ? "moderate" : "low",
    confidenceReason: n.evidence.independent.length ? "Collected daily with independent reporting on record." : "No independent reporting on record; the story rests on project claims and posts.",
    body,
    limitations: [a.volumeScope, "Membership is a classification of what a coin is, not affiliation with any named project or person.", n.evidence.note],
  };
}
